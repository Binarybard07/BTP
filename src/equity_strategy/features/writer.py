import pathlib
from typing import Union, List
import pandas as pd

class FeatureDatasetWriter:
    """
    Dedicated writer for persisting FeatureEngine output DataFrames.

    Maps a raw data directory or raw CSV file path:
        data/raw/{old_folder}/ -> data/raw/{old_folder}_features/
        {SYMBOL}.csv           -> {SYMBOL}_feature.csv
    """

    def get_feature_directory(self, raw_path: Union[str, pathlib.Path]) -> pathlib.Path:
        """
        Derives the output feature directory by appending '_features' to the raw data folder name.
        """
        raw_p = pathlib.Path(raw_path)
        if raw_p.suffix.lower() == ".csv" or (raw_p.exists() and raw_p.is_file()):
            folder = raw_p.parent
        else:
            folder = raw_p

        return folder.parent / f"{folder.name}_features"

    def write(
        self,
        raw_path: Union[str, pathlib.Path],
        df: pd.DataFrame
    ) -> List[pathlib.Path]:
        """
        Writes the FeatureEngine output DataFrame to feature CSV files in the derived feature directory.

        - Automatically derives output directory by appending '_features' to raw folder name.
        - Automatically derives output filenames by appending '_feature.csv' to symbol names.
        - Creates the feature directory if it does not exist.
        - Overwrites existing feature CSVs.
        - Retains Date, Symbol, and original OHLCV columns.
        - Dynamically preserves all feature columns without hardcoding feature names.
        - Preserves NaN values generated by insufficient history.
        - Leaves original raw CSV files untouched.

        :param raw_path: Path to raw CSV file or raw data directory.
        :param df: DataFrame output from FeatureEngine.
        :return: List of written feature CSV file paths.
        """
        if df is None or df.empty:
            return []

        out_dir = self.get_feature_directory(raw_path)
        out_dir.mkdir(parents=True, exist_ok=True)

        written_paths = []

        if "Symbol" not in df.columns:
            raise ValueError(
                "Feature dataset must contain a 'Symbol' column."
            )

        for symbol, group in df.groupby("Symbol", group_keys=False):
            filename = f"{symbol}_feature.csv"
            filepath = out_dir / filename
            group.to_csv(filepath, index=False)
            written_paths.append(filepath)

        return written_paths
